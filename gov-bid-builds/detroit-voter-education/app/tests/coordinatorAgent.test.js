// Hermetic test for STORY-011 (CoordinatorAgent: hold summaries for admin
// review). Uses in-memory doubles -- no live Postgres required. Run with
// `node --test app/tests` (see package.json's "test" script).
const test = require('node:test');
const assert = require('node:assert/strict');

const { createCoordinatorAgent } = require('../agents/coordinatorAgent');
const { createInMemorySummaryRepository } = require('../services/inMemorySummaryRepository');
const { createInMemoryAdminNotifier } = require('../services/inMemoryAdminNotifier');
const { createInMemoryAuditLog } = require('../services/inMemoryAuditLog');
const { generateStubSummary } = require('../agents/summaryGenerationAgentStub');

const NOTIFICATION_SLA_MS = 15 * 60 * 1000; // REQ-003 acceptance criteria: 15 minutes

function buildAgent() {
    const repository = createInMemorySummaryRepository();
    const notifier = createInMemoryAdminNotifier();
    const auditLog = createInMemoryAuditLog();
    const agent = createCoordinatorAgent({ repository, notifier, auditLog });
    return { agent, repository, notifier, auditLog };
}

test('Given a summary generated by SummaryGenerationAgent, When CoordinatorAgent receives it, Then it is held pending review with a notification within 15 minutes', async () => {
    const { agent, notifier, auditLog } = buildAgent();
    const generated = generateStubSummary({ zipCode: '48226', issue: 'housing' });

    const { summary, notification, notificationLatencyMs } = await agent.receiveSummary(generated);

    assert.equal(summary.status, 'pending_review', 'summary must be held in pending_review, not auto-published');
    assert.equal(summary.created_by, 'SummaryGenerationAgent');
    assert.ok(notification.notification_id, 'a notification record must exist');
    assert.equal(notification.summary_id, summary.summary_id);
    assert.ok(
        notificationLatencyMs <= NOTIFICATION_SLA_MS,
        `notification latency ${notificationLatencyMs}ms must be <= ${NOTIFICATION_SLA_MS}ms (15 min SLA)`
    );
    assert.equal(notifier._notifications.length, 1, 'exactly one notification was recorded');
});

test('receiveSummary writes an append-only audit trail for both the hold and the notification', async () => {
    const { agent, auditLog } = buildAgent();
    await agent.receiveSummary(generateStubSummary());

    const actions = auditLog._entries.map((e) => e.action);
    assert.deepEqual(actions, ['SUMMARY_HELD_FOR_REVIEW', 'ADMIN_NOTIFICATION_SENT']);
});

test('receiveSummary rejects empty content rather than holding a blank summary', async () => {
    const { agent } = buildAgent();
    await assert.rejects(() => agent.receiveSummary({ content: '   ', createdBy: 'SummaryGenerationAgent' }));
});

test('listPendingForReview returns only pending_review summaries, oldest first', async () => {
    const { agent, repository } = buildAgent();
    const first = await agent.receiveSummary(generateStubSummary({ issue: 'housing' }));
    const second = await agent.receiveSummary(generateStubSummary({ issue: 'education' }));
    await repository.setStatus(first.summary.summary_id, 'approved', 'ali');

    const pending = await agent.listPendingForReview();

    assert.equal(pending.length, 1);
    assert.equal(pending[0].summary_id, second.summary.summary_id);
});

test('recordAdminDecision approves a summary and writes an audit entry', async () => {
    const { agent, auditLog } = buildAgent();
    const { summary } = await agent.receiveSummary(generateStubSummary());

    const updated = await agent.recordAdminDecision(summary.summary_id, 'approved', 'ram');

    assert.equal(updated.status, 'approved');
    assert.equal(updated.approved_by, 'ram');
    assert.ok(auditLog._entries.some((e) => e.action === 'SUMMARY_APPROVED'));
});

test('recordAdminDecision rejects an unknown decision value', async () => {
    const { agent } = buildAgent();
    const { summary } = await agent.receiveSummary(generateStubSummary());
    await assert.rejects(() => agent.recordAdminDecision(summary.summary_id, 'maybe', 'ram'));
});
